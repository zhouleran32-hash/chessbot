"""Chapter 8: endgame methods, precise theoretical cases, and practical decisions.

Book diagrams are identified in replay titles. Other positions are original
simplifying illustrations. Replies are illustrative unless explicitly forced.
"""
from core.primer_build import after, custom, lesson, step
from core.primer_guides_chapter1 import example

LESSONS = []
EXAMPLES = {}


def add(key, title, summary, pieces, moves, notes, prompt, correct, wrong, *, turn='w', quiz_at=0, label='Original simplifying illustration', objective=None):
    fen = custom(pieces, turn=turn)
    replay = example(label, fen, moves, notes)
    EXAMPLES['ch8-' + key] = [replay]
    quiz = after(moves[:quiz_at], fen)
    LESSONS.append(lesson(8, 'ch8-' + key, title, summary,
        [step(fen, notes[0]), step(quiz, 'Calculation checkpoint: name the threat, predict the reply, then carry out the exact task.')],
        prompt, [(correct[0], True, correct[1])] + [(san, False, feedback) for san, feedback in wrong], objective=objective))


def extra(key, pieces, moves, notes, *, turn='w', label='Original contrasting illustration'):
    EXAMPLES['ch8-' + key].append(example(label, custom(pieces, turn=turn), moves, notes))


